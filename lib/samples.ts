import type { Memory, Photo, Book } from "./model";
const picture = (
  name: string,
  note: string,
  width = 1920,
  height = 1280,
): Photo => ({
  id: name,
  name: name + ".webp",
  type: "image/webp",
  width,
  height,
  original: "/photos/" + name + ".webp",
  preview: "/photos/" + name + ".webp",
  thumb: "/photos/" + name + "-thumb.webp",
  note,
});
function sample(
  id: string,
  title: string,
  body: string,
  date: string,
  places: string[],
  people: string[],
  photos: Photo[],
): Memory {
  return {
    id: "sample-" + id,
    kind: "memory",
    title,
    body,
    date,
    places,
    people,
    photos,
    cover: photos[0]?.id || "",
    created: Date.parse(date + "T12:00:00Z"),
    updated: 0,
    notes: [],
  };
}
